/**
 * Regenerates lib/image-sizes.ts from the files under public/assets.
 *
 * Run after adding or replacing a bundled image:
 *   npm run images:manifest
 *
 * Reads the intrinsic size out of each file's header directly, so the script
 * has no dependencies beyond Node.
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.join(root, "..");
const assetsDir = path.join(projectRoot, "public", "assets");
const outFile = path.join(projectRoot, "lib", "image-sizes.ts");

/** PNG: width and height are two big-endian 32-bit ints in the IHDR chunk. */
function pngSize(buf) {
  if (buf.length < 24) return null;
  if (buf.readUInt32BE(0) !== 0x89504e47) return null;
  return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}

/** JPEG: scan the marker segments for a start-of-frame, which carries the size. */
function jpegSize(buf) {
  if (buf.length < 4 || buf[0] !== 0xff || buf[1] !== 0xd8) return null;

  let offset = 2;
  while (offset < buf.length - 9) {
    if (buf[offset] !== 0xff) {
      offset++;
      continue;
    }
    const marker = buf[offset + 1];
    // SOF0-SOF15, excluding the non-frame markers DHT (c4), JPG (c8) and DAC (cc).
    const isStartOfFrame =
      marker >= 0xc0 && marker <= 0xcf && marker !== 0xc4 && marker !== 0xc8 && marker !== 0xcc;

    if (isStartOfFrame) {
      return { height: buf.readUInt16BE(offset + 5), width: buf.readUInt16BE(offset + 7) };
    }

    const length = buf.readUInt16BE(offset + 2);
    if (length < 2) return null;
    offset += 2 + length;
  }
  return null;
}

async function walk(dir) {
  const found = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) found.push(...(await walk(full)));
    else found.push(full);
  }
  return found;
}

const files = (await walk(assetsDir)).sort();
const entries = [];

for (const file of files) {
  const ext = path.extname(file).toLowerCase();
  if (![".png", ".jpg", ".jpeg"].includes(ext)) continue;

  const buf = await readFile(file);
  const size = ext === ".png" ? pngSize(buf) : jpegSize(buf);
  if (!size) {
    console.warn("could not read dimensions:", path.relative(projectRoot, file));
    continue;
  }

  const url = "/" + path.relative(path.join(projectRoot, "public"), file).split(path.sep).join("/");
  entries.push({ url, ...size });
}

const body = entries
  .map((e) => `  "${e.url}": { width: ${e.width}, height: ${e.height} },`)
  .join("\n");

await writeFile(
  outFile,
  `/**
 * Intrinsic dimensions of every bundled image under /public/assets.
 *
 * next/image needs width and height to reserve layout space before the file
 * arrives, which is what keeps Cumulative Layout Shift at zero. Keeping them in
 * a generated map means markup does not have to repeat numbers that can drift
 * out of sync with the files.
 *
 * Generated by scripts/generate-image-manifest.mjs - do not edit by hand.
 * Regenerate after adding or replacing an asset:
 *   npm run images:manifest
 */
export type ImageSize = { width: number; height: number };

export const IMAGE_SIZES: Record<string, ImageSize> = {
${body}
};

/** Dimensions for a bundled asset, or undefined for remote/CMS images. */
export function imageSize(src: string): ImageSize | undefined {
  return IMAGE_SIZES[src];
}
`,
  "utf8"
);

console.log(`wrote ${path.relative(projectRoot, outFile)} with ${entries.length} entries`);
